# 1. Load the data (make sure files are uploaded on the left side)
books = pd.read_csv('BX_Books.csv', sep=';', encoding='latin-1', low_memory=False, on_bad_lines='skip')
ratings = pd.read_csv('BX-Book-Ratings.csv', sep=';', encoding='latin-1', low_memory=False, on_bad_lines='skip')

# 2. Rename columns to match properly
books.columns = ['ISBN', 'Book-Title', 'Book-Author', 'Year-Of-Publication', 'Publisher', 'Image-URL-S', 'Image-URL-M', 'Image-URL-L']

# 3. Create 'ratings_with_books'
ratings_with_books = ratings.merge(books, on='ISBN')

# 4. Now run your Step 3 calculation safely!
num_rating_df = ratings_with_books.groupby('Book-Title').count()['Book-Rating'].reset_index()
num_rating_df.rename(columns={'Book-Rating': 'num_ratings'}, inplace=True)

avg_rating_df = ratings_with_books.groupby('Book-Title').mean(numeric_only=True)['Book-Rating'].reset_index()
avg_rating_df.rename(columns={'Book-Rating': 'avg_rating'}, inplace=True)

popular_df = num_rating_df.merge(avg_rating_df, on='Book-Title')
popular_df = popular_df[popular_df['num_ratings'] >= 250].sort_values(by='avg_rating', ascending=False).head(50)
popular_df = popular_df.merge(books, on='Book-Title').drop_duplicates('Book-Title')

print("Success! Popular books loaded.")
print(popular_df[['Book-Title', 'Book-Author', 'num_ratings', 'avg_rating']].head(5))

import numpy as np
from sklearn.metrics.pairwise import cosine_similarity

# 1. Filter active users who have rated more than 200 books
user_counts = ratings_with_books.groupby('User-ID').count()['Book-Rating'] > 200
active_users = user_counts[user_counts].index
filtered_rating = ratings_with_books[ratings_with_books['User-ID'].isin(active_users)]

# 2. Filter popular books that have received at least 50 ratings
book_counts = filtered_rating.groupby('Book-Title').count()['Book-Rating'] >= 50
famous_books = book_counts[book_counts].index
final_ratings = filtered_rating[filtered_rating['Book-Title'].isin(famous_books)]

# 3. Create Pivot Table (Rows: Book-Title, Columns: User-ID, Values: Book-Rating)
pt = final_ratings.pivot_table(index='Book-Title', columns='User-ID', values='Book-Rating')
pt.fillna(0, inplace=True)

# 4. Compute Cosine Similarity Matrix
similarity_scores = cosine_similarity(pt)

print("Collaborative filtering matrix and similarity scores created successfully!")
print("Pivot table shape (Books x Users):", pt.shape)

def recommend(book_name):
    # Check if the book exists in our pivot table index
    if book_name not in pt.index:
        return f"'{book_name}' not found in the database. Try another popular book!"

    # Get the index of the book in the pivot table
    index = np.where(pt.index == book_name)[0][0]

    # Sort the similarity scores for this book (skip index 0 which is the book itself)
    similar_items = sorted(list(enumerate(similarity_scores[index])), key=lambda x: x[1], reverse=True)[1:6]

    recommended_books = []
    for i in similar_items:
        book_title = pt.index[i[0]]
        recommended_books.append(book_title)

    return recommended_books

